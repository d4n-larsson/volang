#!/usr/bin/env python3
"""Writes src/case_table.h (spec 042): the simple case mappings `upper` and `lower` apply outside ASCII.

For every code point of Latin-1 Supplement, Latin Extended-A and -B (U+0080 to U+024F) and of Greek and
Coptic, Cyrillic and Cyrillic Supplement (U+0370 to U+052F): the pair (from, to) when Python's
str.upper() or str.lower() of that one character is one other code point. Characters whose only
mapping is several characters (ß, ŉ, ǰ, ΐ) have no pair and stay as they are.

  gen_case.py           prints the header (tests/strings.py compares it with the checked-in file)
  gen_case.py --write   writes src/case_table.h
"""
import os
import sys

RANGES = [(0x80, 0x24F), (0x370, 0x52F)]


def pairs(fn):
    out = []
    for lo, hi in RANGES:
        for cp in range(lo, hi + 1):
            to = fn(chr(cp))
            if len(to) == 1 and to != chr(cp):
                out.append((cp, ord(to)))
    return out


def table(name, ps):
    rows = ["static const unsigned int %s[][2] = {" % name]
    for i in range(0, len(ps), 6):
        rows.append("    " + " ".join("{0x%04X, 0x%04X}," % p for p in ps[i:i + 6]))
    rows.append("};")
    return "\n".join(rows)


def header():
    up, low = pairs(str.upper), pairs(str.lower)
    return ("/* Generated by tools/gen_case.py from Python's Unicode data: do not edit. Simple (one code point)\n"
            " * case mappings for U+0080-U+024F and U+0370-U+052F, sorted by the first column. */\n"
            + table("case_upper", up) + "\n\n" + table("case_lower", low) + "\n")


if __name__ == "__main__":
    text = header()
    if "--write" in sys.argv:
        path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src", "case_table.h")
        open(path, "w").write(text)
    else:
        sys.stdout.write(text)
